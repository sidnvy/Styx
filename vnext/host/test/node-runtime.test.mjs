import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {createHash,generateKeyPairSync,sign} from 'node:crypto';
import {stageSignedRelease,refreshVerifiedBootstrap,activateRelease,verifiedServiceNode} from '../installer.mjs';
import {writePrivateFile} from '../private-storage.mjs';
const hash=b=>createHash('sha256').update(b).digest('hex');
test('Windows runtime preflight refuses change before any bootstrap replacement',t=>{
  const root=fs.mkdtempSync(path.join(os.tmpdir(),'styx-node-'));
  t.after(()=>fs.rmSync(root,{recursive:true,force:true}));
  const {privateKey,publicKey}=generateKeyPairSync('ed25519');
  const pem=publicKey.export({type:'spki',format:'pem'});
  const source=path.join(root,'source'),installRoot=path.join(root,'install');
  fs.mkdirSync(source);fs.mkdirSync(path.join(source,'host'));fs.mkdirSync(path.join(source,'bin'));
  const files=['host/installer.mjs','host/launch.mjs','bin/node.exe'].map(name=>{
    const b=Buffer.from('signed '+name);fs.writeFileSync(path.join(source,name),b);
    return {path:name,size:b.length,sha256:hash(b),executable:name.startsWith('bin/')};
  });
  const raw=JSON.stringify({schema:1,version:'node-test',platform:'win32',arch:'x64',files});
  fs.writeFileSync(path.join(source,'manifest.json'),raw);
  fs.writeFileSync(path.join(source,'manifest.sig'),sign(null,Buffer.from(raw),privateKey).toString('base64url'));
  const options={platform:'win32',arch:'x64'};
  stageSignedRelease({sourceDir:source,installRoot,publicKeyPem:pem,...options});
  const before=fs.readFileSync(path.join(installRoot,'installer.mjs'));
  writePrivateFile(path.join(installRoot,'node.exe'),'old locked runtime');
  assert.throws(()=>refreshVerifiedBootstrap(installRoot,pem,'node-test',options),/requires_offline_switch/);
  assert.deepEqual(fs.readFileSync(path.join(installRoot,'installer.mjs')),before);
  fs.writeFileSync(path.join(installRoot,'node.exe'),fs.readFileSync(path.join(source,'bin/node.exe')));
  assert.equal(refreshVerifiedBootstrap(installRoot,pem,'node-test',options).status,'bootstrap_refreshed');
  assert.equal(fs.readFileSync(path.join(installRoot,'node.exe'),'utf8'),'signed bin/node.exe');
  fs.rmSync(path.join(installRoot,'node.exe'));
  assert.equal(refreshVerifiedBootstrap(installRoot,pem,'node-test',options).status,'bootstrap_refreshed');
  assert.equal(fs.readFileSync(path.join(installRoot,'node.exe'),'utf8'),'signed bin/node.exe');
});

test('service runtime selection accepts only signed stable or active-generation Node',t=>{
  const root=fs.mkdtempSync(path.join(os.tmpdir(),'styx-service-node-'));
  t.after(()=>fs.rmSync(root,{recursive:true,force:true}));
  const {privateKey,publicKey}=generateKeyPairSync('ed25519');
  const pem=publicKey.export({type:'spki',format:'pem'});
  const source=path.join(root,'source'),installRoot=path.join(root,'install');
  fs.mkdirSync(source);fs.mkdirSync(path.join(source,'host'));fs.mkdirSync(path.join(source,'bin'));
  const name=process.platform==='win32'?'node.exe':'node';
  const files=['host/installer.mjs','host/launch.mjs','bin/'+name].map(p=>{
    const b=Buffer.from('signed '+p);fs.writeFileSync(path.join(source,p),b);
    return {path:p,size:b.length,sha256:hash(b),executable:p.startsWith('bin/')};
  });
  const raw=JSON.stringify({schema:1,version:'service-node',platform:process.platform,arch:process.arch,files});
  fs.writeFileSync(path.join(source,'manifest.json'),raw);
  fs.writeFileSync(path.join(source,'manifest.sig'),sign(null,Buffer.from(raw),privateKey).toString('base64url'));
  stageSignedRelease({sourceDir:source,installRoot,publicKeyPem:pem});
  activateRelease(installRoot,'service-node',pem);
  refreshVerifiedBootstrap(installRoot,pem,'service-node');
  const args={installRoot,publicKeyPem:pem};
  const stable=path.join(installRoot,name);
  assert.equal(verifiedServiceNode(args),stable);
  assert.throws(()=>verifiedServiceNode({...args,nodeBinary:process.execPath}),/outside_signed_install/);
  fs.writeFileSync(stable,'modified stable runtime');
  assert.throws(()=>verifiedServiceNode(args),/service_node_hash_mismatch/);
  const generation=path.join(installRoot,'releases','service-node','bin',name);
  assert.equal(verifiedServiceNode({...args,nodeBinary:generation}),generation);
});
